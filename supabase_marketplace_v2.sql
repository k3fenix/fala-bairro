-- POLÍTICAS DE SEGURANÇA (RLS)
-- Como no app atual ainda estamos migrando para uma autenticação estrita no backend, 
-- vamos usar permissões balanceadas (como `USING (true)` para leitura).

-- Settings e Categorias: Todos podem ler, ninguém (além do admin via role no app) pode alterar.
CREATE POLICY "Permitir leitura para todos em settings" ON public.marketplace_settings FOR SELECT USING (true);
CREATE POLICY "Permitir leitura para todos em categories" ON public.marketplace_categories FOR SELECT USING (true);
CREATE POLICY "Permitir edição para todos em categories" ON public.marketplace_categories FOR ALL USING (true);
CREATE POLICY "Permitir leitura para todos em subcategories" ON public.marketplace_subcategories FOR SELECT USING (true);
CREATE POLICY "Permitir edição para todos em subcategories" ON public.marketplace_subcategories FOR ALL USING (true);
CREATE POLICY "Permitir edição para todos em settings" ON public.marketplace_settings FOR ALL USING (true);

-- Listings (Anúncios): Todos podem ler e inserir, atualizar/deletar fica por conta do App verificar se é o dono ou admin
CREATE POLICY "Permitir tudo listings" ON public.marketplace_listings FOR ALL USING (true);

-- Imagens: Todos podem ler e inserir
CREATE POLICY "Permitir tudo images" ON public.marketplace_listing_images FOR ALL USING (true);

-- Favoritos: Todos podem ler e inserir
CREATE POLICY "Permitir tudo favorites" ON public.marketplace_favorites FOR ALL USING (true);

-- Denúncias: Todos podem ler e inserir
CREATE POLICY "Permitir tudo reports" ON public.marketplace_reports FOR ALL USING (true);

-- Reviews: Todos podem ler e inserir
CREATE POLICY "Permitir tudo reviews" ON public.marketplace_reviews FOR ALL USING (true);
