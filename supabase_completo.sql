-- 1. TABELA DE PERFIS DE USUÁRIOS
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    handle TEXT UNIQUE,
    status TEXT DEFAULT 'Ativo',
    avatar TEXT,
    whatsapp TEXT,
    neighborhood TEXT,
    address TEXT,
    role TEXT DEFAULT 'user'
);

-- 2. TABELA DE PUBLICAÇÕES DO MURAL / NOTÍCIAS
CREATE TABLE IF NOT EXISTS public.posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    author_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    author_name TEXT NOT NULL,
    author_avatar TEXT,
    handle TEXT,
    category TEXT DEFAULT 'Geral',
    neighborhood TEXT NOT NULL,
    content TEXT,
    image TEXT,
    likes INTEGER DEFAULT 0,
    upvotes INTEGER DEFAULT 0,
    downvotes INTEGER DEFAULT 0,
    is_pending BOOLEAN DEFAULT false,
    is_approved BOOLEAN DEFAULT true
);

-- 3. TABELA DE COMENTÁRIOS
CREATE TABLE IF NOT EXISTS public.comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    post_id BIGINT REFERENCES public.posts(id) ON DELETE CASCADE,
    author_name TEXT NOT NULL,
    text TEXT NOT NULL
);

-- 4. TABELA DE CONFIGURAÇÕES GERAIS
CREATE TABLE IF NOT EXISTS public.settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key TEXT UNIQUE NOT NULL,
    value TEXT NOT NULL
);

-- 5. TABELA DE PETS PERDIDOS E ACHADOS
CREATE TABLE IF NOT EXISTS public.lost_pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    pet_name TEXT NOT NULL,
    species TEXT NOT NULL,
    description TEXT,
    last_seen_location TEXT NOT NULL,
    owner_whatsapp TEXT NOT NULL,
    image TEXT,
    status TEXT DEFAULT 'Perdido' -- 'Perdido', 'Encontrado' ou 'Achado'
);

-- 6. TABELA DO GUIA COMERCIAL
CREATE TABLE IF NOT EXISTS public.commercial_guide (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT,
    whatsapp TEXT NOT NULL,
    neighborhood TEXT DEFAULT 'Geral',
    rating NUMERIC DEFAULT 5.0,
    is_verified BOOLEAN DEFAULT true,
    image TEXT
);

-- 7. TABELA DE SOLICITAÇÕES DE EXCLUSÃO DE CONTA
CREATE TABLE IF NOT EXISTS public.deletion_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    user_name TEXT NOT NULL,
    user_whatsapp TEXT NOT NULL,
    status TEXT DEFAULT 'Pendente'
);

-- 8. CONFIGURAÇÕES DO MARKETPLACE E ADMINISTRADOR
CREATE TABLE IF NOT EXISTS public.marketplace_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    description TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

