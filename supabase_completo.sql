-- Script SQL Completo do Fala Bairro
-- Este script cria todas as tabelas, configura o RLS e adiciona os dados iniciais.
-- Execute no SQL Editor do Supabase.

-- 1. Tabela de Usuários
CREATE TABLE public.profiles (
    id UUID DEFAULT auth.uid() PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    handle TEXT UNIQUE NOT NULL,
    status TEXT DEFAULT 'Ativo',
    avatar TEXT,
    whatsapp TEXT,
    neighborhood TEXT,
    address TEXT,
    role TEXT DEFAULT 'user'
);

-- 2. Tabela de Publicações (Posts)
CREATE TABLE public.posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    author_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    author_name TEXT NOT NULL,
    author_avatar TEXT,
    handle TEXT NOT NULL,
    category TEXT DEFAULT 'Geral',
    neighborhood TEXT NOT NULL,
    content TEXT,
    image TEXT,
    likes INTEGER DEFAULT 0,
    upvotes INTEGER DEFAULT 0,
    downvotes INTEGER DEFAULT 0,
    is_pending BOOLEAN DEFAULT true,
    is_approved BOOLEAN DEFAULT false
);

-- 3. Tabela de Comentários
CREATE TABLE public.comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    post_id BIGINT REFERENCES public.posts(id) ON DELETE CASCADE,
    author_name TEXT NOT NULL,
    text TEXT NOT NULL
);

-- 4. Tabela de Configurações Globais
CREATE TABLE public.settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key TEXT UNIQUE NOT NULL,
    value TEXT NOT NULL
);

-- 5. Tabela de Pets Perdidos
CREATE TABLE public.lost_pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    pet_name TEXT NOT NULL,
    species TEXT NOT NULL,
    description TEXT,
    last_seen_location TEXT NOT NULL,
    owner_whatsapp TEXT NOT NULL,
    image TEXT,
    status TEXT DEFAULT 'Perdido' -- Pode ser 'Perdido' ou 'Encontrado'
);

-- 6. Tabela de Vendas & Trocas (Marketplace)
CREATE TABLE public.marketplace_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    seller_name TEXT NOT NULL,
    seller_whatsapp TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    price NUMERIC,
    type TEXT DEFAULT 'Venda', -- 'Venda', 'Troca', 'Grátis'
    condition TEXT DEFAULT 'Usado', -- 'Novo', 'Usado'
    neighborhood TEXT NOT NULL,
    image TEXT,
    status TEXT DEFAULT 'Ativo' -- 'Ativo', 'Vendido'
);

-- 7. Tabela do Guia Comercial
CREATE TABLE public.commercial_guide (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT,
    whatsapp TEXT NOT NULL,
    neighborhood TEXT DEFAULT 'Geral',
    rating NUMERIC DEFAULT 5.0,
    is_verified BOOLEAN DEFAULT true,
    image TEXT
);

-- 8. Tabela de solicitações de exclusão de conta
CREATE TABLE public.deletion_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    user_name TEXT NOT NULL,
    user_whatsapp TEXT NOT NULL,
    status TEXT DEFAULT 'Pendente' -- Pode ser 'Pendente' ou 'Excluída'
);


-- HABILITAR RLS (Row Level Security) EM TODAS AS TABELAS
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lost_pets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.marketplace_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.commercial_guide ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.deletion_requests ENABLE ROW LEVEL SECURITY;


-- CRIAR POLÍTICAS DE SEGURANÇA (PERMISSÃO TOTAL NESTA FASE DE DESENVOLVIMENTO)
CREATE POLICY "Permitir tudo profiles" ON public.profiles FOR ALL USING (true);
CREATE POLICY "Permitir tudo posts" ON public.posts FOR ALL USING (true);
CREATE POLICY "Permitir tudo comments" ON public.comments FOR ALL USING (true);
CREATE POLICY "Permitir tudo settings" ON public.settings FOR ALL USING (true);
CREATE POLICY "Permitir tudo lost_pets" ON public.lost_pets FOR ALL USING (true);
CREATE POLICY "Permitir tudo marketplace" ON public.marketplace_items FOR ALL USING (true);
CREATE POLICY "Permitir tudo commercial_guide" ON public.commercial_guide FOR ALL USING (true);
CREATE POLICY "Permitir tudo deletion_requests" ON public.deletion_requests FOR ALL USING (true);


